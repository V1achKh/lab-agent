CIRCUIT_FORMAT = """\
Формат описания цепи (JSON):
{
  "title": "короткое название цепи",
  "elements": [
    {"name": "E1",  "type": "V",  "n1": "1", "n2": "0", "value": 15},
    {"name": "R1",  "type": "R",  "n1": "1", "n2": "2", "value": "1k"},
    {"name": "R2",  "type": "R",  "n1": "2", "n2": "0", "value": "2k"},
    {"name": "J",   "type": "I",  "n1": "0", "n2": "2", "value": "25m"},
    {"name": "PV1", "type": "VM", "n1": "2", "n2": "0", "r": "500k"}
  ],
  "analyses": [{"type": "op"}]
}
Правила:
- Узел — это точка, где соединяются выводы. Все точки, соединённые проводом без элементов, — ОДИН узел.
  Один из узлов (обычно нижний провод) назови "0" — общий провод. Остальные: "1", "2", "3"...
- type: R (резистор, Ом), C (Ф), L (Гн), V (источник ЭДС, В), I (источник тока, А),
  AM (амперметр, r — внутреннее сопротивление, Ом), VM (вольтметр, r — внутреннее сопротивление, Ом).
- Источник ЭДС: n1 — положительная клемма. На схемах стрелка внутри источника ЭДС указывает на «+» (это n1).
- Источник тока: ток течёт от n1 через источник к n2. Стрелка (двойная «галочка») указывает на n2.
- Амперметр включается В РАЗРЫВ ветви (последовательно): между двумя разными узлами.
- Вольтметр подключается ПАРАЛЛЕЛЬНО участку: n1 — точка с «+», n2 — точка с «−».
- value: число в СИ или строка с множителем: "1k" (кОм), "25m" (мА), "500k", "0.1u", "1M" (мега).
  На схемах заданий «1 к» означает 1 кОм.
- analyses: {"type": "op"} — постоянный ток; {"type": "ac", "f_start": 10, "f_stop": 100000} —
  частотные характеристики; {"type": "tran", "t_stop": 0.5} — переходный процесс.
- Позиционные обозначения — как в задании (R1, E1, J, ...); приборы — PV1 (вольтметр), PA1 (амперметр).
  Если на картинке у элементов нет обозначений, а только номиналы («1 к», «15 В», «5 мА»), назови их
  сам по порядку: резисторы R1, R2…, источники напряжения E1, E2…, источники тока J1, J2….
- Число рядом с прибором на картинке (например «0,05» у амперметра или «500 к» у вольтметра) — это
  его внутреннее сопротивление r. Прибор на картинке показывает, ЧТО нужно определить: амперметр —
  ток в ветви, где он стоит; вольтметр — напряжение между точками, к которым он подключён.

Лабораторная работа №1 «Цепи постоянного тока»: в цепь добавь РОВНО ОДИН прибор — тот, которым
по заданию измеряют искомую величину (вольтметр параллельно участку или амперметр в разрыв ветви),
с внутренним сопротивлением из задания. Анализ — только {"type": "op"}.
"""

